#!/usr/bin/env python3
"""Generate llama.cpp router presets, one file per VRAM tier and profile.

llama.cpp's preset format has no include directive (see common/preset.cpp:
parse_ini_from_file accepts only header / key=value / comment / blank lines),
so tier files are generated by concatenation rather than composed at runtime.

Three things compete for the same VRAM: weight quantisation, context length and
KV cache precision. Each profile spends the budget differently:

  quality   lossless KV cache, best quant, then as much context as fits
  balanced  near-lossless q8_0 KV, at least 64K context, then the best quant
  context   most context first, trading KV precision down to q4_0 to get it

Sources:
  configs/<provider>/<model>.ini  one section per model, tuning only, no paths
  configs/vram-estimates.json     gguf-parser measurements

Output:
  dist/vram-<NN>gb-<profile>.ini

Usage:
    python3 src/build.py            # write dist/
    python3 src/build.py --notes    # print release notes to stdout
"""

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONFIGS = ROOT / "configs"
DIST = ROOT / "dist"

TIERS = [4, 8, 16, 24, 32]
HEADROOM_GIB = 1.0     # left free for the OS / display
MIN_CTX = 4096         # below this a model is not worth shipping
BALANCED_CTX = 65536   # what the balanced profile tries to reach first

# Highest fidelity first. f16 is lossless; q4_0 is the cheapest we will ship.
KV_FIDELITY = ["f16", "q8_0", "q5_1", "q4_0"]

PROFILES = {
    "quality":  {
        "kv": ["f16", "q8_0"],
        "blurb": "lossless KV cache, best quantisation, then as much context as fits",
    },
    "balanced": {
        "kv": ["q8_0"],
        "blurb": "q8_0 KV cache, at least 64K context, then the best quantisation",
    },
    "context":  {
        "kv": ["q8_0", "q5_1", "q4_0"],
        "blurb": "most context first, trading KV cache precision down to q4_0 to get it",
    },
}

HEADER = """version = 1

; llama.cpp router preset - {tier} GB VRAM, {profile} profile
;
; {blurb}
;
; GENERATED by src/build.py - do not edit.
; Edit configs/<provider>/<model>.ini and re-run: python3 src/build.py
;
; Models are located by --models-dir. Each section name must exactly match a
; subdirectory under that root; no paths appear in this file. See README.md.
;
;   llama-server --models-dir /path/to/models \\
;                --models-preset dist/vram-{tier:02d}gb-{profile}.ini \\
;                --host 127.0.0.1 --port 8080
;
; Download the quant listed below into the matching directory. Figures are
; gguf-parser estimates with flash-attn on and full GPU offload, reserving
; {headroom:.0f} GiB for the OS/display. KV cache type is set per model.
;
; A model you have not downloaded still appears here. Requesting it stalls the
; client until it gives up, so delete sections you do not intend to use.
;
{table};

[*]
stop-timeout = 30
cache-prompt = true
jinja = true
flash-attn = auto
reasoning-format = auto
"""


def load_model_configs():
    """One dict per config, sorted by path."""
    out = []
    for path in sorted(CONFIGS.rglob("*.ini")):
        text = path.read_text()
        m = re.search(r"^\[([^\]]+)\]", text, re.M)
        if not m:
            sys.exit(f"{path}: no [section] found")
        head = text[: m.start()]
        doc = [l for l in head.splitlines() if l.strip().startswith(";")]

        def field(name):
            hit = re.search(rf"^;\s*{name}:\s*(.+)$", head, re.M)
            return hit.group(1).strip() if hit else ""

        cap, body = None, []
        for line in text[m.start():].rstrip().splitlines():
            key = line.split("=", 1)[0].strip() if "=" in line else ""
            if key == "ctx-size":
                cap = int(line.split("=", 1)[1].strip())   # a cap, never exceeded
                continue
            body.append(line)

        title = doc[0].lstrip("; ").strip() if doc else m.group(1)
        out.append({
            "provider": path.parent.name,
            "id": m.group(1).strip(),
            "title": title,
            "params": field("params"),
            "tags": [t.strip() for t in field("tags").split(",") if t.strip()],
            "doc": doc,
            "body": body,
            "cap": cap,
        })
    return out


def vram(data, quant, ctx, kv):
    """VRAM of a (quant, context, KV type) triple.

    KV cost per token does not depend on the weight quant, so every quant's
    curve is the matching reference curve shifted by a constant.
    """
    offset = data["quants"][quant] - data["quants"][data["ref_quant"]]
    return data["ref_curves"][kv][str(ctx)] + offset


def candidates(data, budget, cap, kv_allowed):
    """[(kv, quant, ctx, gib)] that fit the budget."""
    out = []
    for kv in kv_allowed:
        curve = data["ref_curves"].get(kv)
        if not curve:
            continue
        ladder = sorted(int(c) for c in curve)
        if cap:
            ladder = [c for c in ladder if c <= cap]
        for quant in data["quants"]:
            for ctx in ladder:
                if ctx < MIN_CTX and ctx != ladder[-1]:
                    continue
                gib = vram(data, quant, ctx, kv)
                if gib <= budget:
                    out.append((kv, quant, ctx, gib))
    return out


def pick(data, budget, profile, cap):
    """Choose (kv, quant, ctx, gib) for a profile, or None if nothing fits."""
    spec = PROFILES[profile]
    opts = candidates(data, budget, cap, spec["kv"])
    if not opts:
        return None

    qrank = {q: i for i, q in enumerate(sorted(data["quants"], key=lambda q: data["quants"][q]))}
    # higher is better fidelity
    krank = {kv: len(KV_FIDELITY) - KV_FIDELITY.index(kv) for kv in KV_FIDELITY}

    if profile == "quality":
        return max(opts, key=lambda o: (krank[o[0]], qrank[o[1]], o[2]))
    if profile == "context":
        return max(opts, key=lambda o: (o[2], qrank[o[1]], krank[o[0]]))

    # balanced: reach the target context first, then buy quality with the rest
    target = min(BALANCED_CTX, max(o[2] for o in opts))
    good = [o for o in opts if o[2] >= target] or opts
    best_q = max(qrank[o[1]] for o in good)
    return max((o for o in good if qrank[o[1]] == best_q), key=lambda o: o[2])


def plan(est, models):
    """{(tier, profile): [ {**config, kv, quant, ctx, gib} ]}"""
    out = {}
    for tier in TIERS:
        budget = tier - HEADROOM_GIB
        for profile in PROFILES:
            chosen = []
            for cfg in models:
                got = pick(est["models"][cfg["id"]], budget, profile, cfg["cap"])
                if got:
                    kv, quant, ctx, gib = got
                    chosen.append({**cfg, "kv": kv, "quant": quant, "ctx": ctx, "gib": gib})
            if chosen:
                out[(tier, profile)] = chosen
    return out


def write_dist(built):
    DIST.mkdir(exist_ok=True)
    written = []
    for (tier, profile), chosen in built.items():
        w = max(len(c["id"]) for c in chosen)
        table = "".join(
            f";   {c['id']:<{w}}  {c['quant']:<12}  {c['ctx']:>7} ctx  "
            f"KV {c['kv']:<5}  {c['gib']:5.1f} GiB\n" for c in chosen
        )
        parts = [HEADER.format(tier=tier, profile=profile, blurb=PROFILES[profile]["blurb"],
                               headroom=HEADROOM_GIB, table=table)]
        for c in chosen:
            parts.append("")
            parts.extend(c["doc"])
            parts.append(f"; this profile: {c['quant']}, {c['ctx']} context, "
                         f"{c['kv']} KV cache (~{c['gib']:.1f} GiB)")
            parts.append(c["body"][0])       # the [section] line
            parts.append(f"ctx-size = {c['ctx']}")
            parts.append(f"cache-type-k = {c['kv']}")
            parts.append(f"cache-type-v = {c['kv']}")
            parts.extend(c["body"][1:])
        path = DIST / f"vram-{tier:02d}gb-{profile}.ini"
        path.write_text("\n".join(parts) + "\n")
        written.append((path, len(chosen)))
    return written


def render_notes(built, est):
    meta = est["_meta"]
    lines = [
        "Ready-to-use llama.cpp router presets, grouped by VRAM budget.",
        "",
        "Weight quantisation, context length and KV cache precision all compete for the same",
        "VRAM. Each budget ships three profiles that spend it differently:",
        "",
        "| Profile | Strategy |",
        "| --- | --- |",
    ]
    for name, spec in PROFILES.items():
        lines.append(f"| `{name}` | {spec['blurb']} |")
    lines += [
        "",
        "Download the one matching your GPU, then start the server:",
        "",
        "```sh",
        "llama-server --models-dir /path/to/models \\",
        "             --models-preset vram-16gb-balanced.ini \\",
        "             --host 127.0.0.1 --port 8080",
        "```",
        "",
        "Model folder names must match the section names in the file. "
        "See the README for the required layout.",
        "",
        "## Contents",
        "",
        "| Profile | " + " | ".join(f"{t} GB" for t in TIERS) + " |",
        "| --- | " + " | ".join("---" for _ in TIERS) + " |",
    ]
    for profile in PROFILES:
        cells = [str(len(built.get((t, profile), []))) for t in TIERS]
        lines.append(f"| `{profile}` | " + " | ".join(cells) + " |")

    lines += ["", "## What each profile picks", ""]
    for (tier, profile), chosen in built.items():
        lines += [
            f"<details><summary><code>vram-{tier:02d}gb-{profile}.ini</code> "
            f"&mdash; {len(chosen)} models</summary>", "",
            "| Model | Quant | Context | KV cache | Est. VRAM |",
            "| --- | --- | --- | --- | --- |",
        ]
        for c in chosen:
            lines.append(f"| `{c['id']}` | `{c['quant']}` | {c['ctx']:,} | "
                         f"`{c['kv']}` | {c['gib']:.1f} GiB |")
        lines += ["", "</details>", ""]

    lines += [
        "---", "",
        f"VRAM measured with {meta['tool']}, flash-attention on, full GPU offload. "
        f"Each profile reserves {HEADROOM_GIB:.0f} GiB for the OS/display.",
    ]
    return "\n".join(lines)


def fmt_ctx(n):
    return f"{n // 1024}K" if n >= 1024 and n % 1024 == 0 else f"{n:,}"


def render_models_md(built, models):
    """Browsable catalogue: what exists, and what each card gets."""
    where = {}   # model_id -> {tier: {profile: pick}}
    for (tier, profile), chosen in built.items():
        for c in chosen:
            where.setdefault(c["id"], {}).setdefault(tier, {})[profile] = c

    lines = [
        "# Model catalogue",
        "",
        "GENERATED by `src/build.py` - do not edit.",
        "",
        f"{len(models)} models. Use this to find a model, check it fits your card, and see",
        "which quantisation and context you get. See the [README](README.md) to get started.",
        "",
        "## All models",
        "",
        "`Smallest card` is the least VRAM that runs the model at all. `Best context` is the",
        "most context any profile reaches on a 32 GB card.",
        "",
        "| Model | Params | Good at | Smallest card | Best context |",
        "| --- | --- | --- | --- | --- |",
    ]
    for cfg in sorted(models, key=lambda c: c["id"]):
        tiers = where.get(cfg["id"], {})
        if not tiers:
            continue
        smallest = f"{min(tiers)} GB"
        best = max(p["ctx"] for p in tiers[max(tiers)].values())
        tags = ", ".join(cfg["tags"]) or "text"
        lines.append(f"| [`{cfg['id']}`](#{cfg['id'].replace('.', '')}) | {cfg['params']} "
                     f"| {tags} | {smallest} | {fmt_ctx(best)} |")

    lines += ["", "## What each card gets", ""]
    for cfg in sorted(models, key=lambda c: c["id"]):
        tiers = where.get(cfg["id"], {})
        if not tiers:
            continue

        lines += [
            f"### {cfg['id']}",
            "",
            cfg["title"],
            "",
            "| Card | Profile | Quant | Context | KV cache | VRAM |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for tier in sorted(tiers):
            for profile in PROFILES:
                p = tiers[tier].get(profile)
                if not p:
                    continue
                lines.append(f"| {tier} GB | `{profile}` | `{p['quant']}` | "
                             f"{fmt_ctx(p['ctx'])} | `{p['kv']}` | {p['gib']:.1f} GiB |")
        lines.append("")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--notes", action="store_true",
                    help="print release notes to stdout instead of writing dist/")
    args = ap.parse_args()

    est = json.loads((CONFIGS / "vram-estimates.json").read_text())
    models = load_model_configs()

    needed = {kv for spec in PROFILES.values() for kv in spec["kv"]}
    incomplete = []
    for cfg in models:
        data = est["models"].get(cfg["id"], {})
        if not data.get("quants") or not needed <= set(data.get("ref_curves", {})):
            incomplete.append(cfg["id"])
    if incomplete:
        sys.exit("missing measurements for: " + ", ".join(incomplete)
                 + "\nrun: python3 src/measure.py --missing")

    built = plan(est, models)

    if args.notes:
        print(render_notes(built, est))
        return

    for path, n in write_dist(built):
        print(f"wrote {path.relative_to(ROOT)}  ({n} models)")

    # Committed, unlike dist/, so it can be browsed on GitHub. CI checks it is fresh.
    catalogue = ROOT / "MODELS.md"
    catalogue.write_text(render_models_md(built, models))
    print(f"wrote {catalogue.relative_to(ROOT)}  ({len(models)} models)")


if __name__ == "__main__":
    main()
