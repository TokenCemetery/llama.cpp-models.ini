#!/usr/bin/env python3
"""Generate llama.cpp router presets, one file per VRAM tier.

llama.cpp's preset format has no include directive (see common/preset.cpp:
parse_ini_from_file accepts only header / key=value / comment / blank lines),
so tier files are generated by concatenation rather than composed at runtime.

Three things compete for the same VRAM: weight quantisation, context length and
KV cache precision. Each profile spends the budget differently:

  quality   lossless KV cache, best quant, then as much context as fits
  balanced  near-lossless q8_0 KV, at least 64K context, then the best quant
  context   most context first, trading KV precision down to q4_0 to get it

All three live in the same tier file, as separate sections named

    <model>-<quant>-<context>-<kv cache type>

because a section only applies to the --models-dir subdirectory with exactly
that name (common/preset.cpp: load_from_models_dir keys presets by directory
name). Encoding the choice in the name is therefore what lets one file carry
several setups for the same model, and it makes profiles that landed on the
same setup collapse into a single section instead of being duplicated.

Sources:
  configs/<provider>/<model>.ini  one section per model, tuning only, no paths
  configs/vram-estimates.json     gguf-parser measurements

Output:
  dist/vram-<NN>gb.ini

Usage:
    python3 src/build.py            # write dist/
    python3 src/build.py --notes    # print release notes to stdout
"""

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONFIGS = ROOT / "configs"
DIST = ROOT / "dist"

TIERS = [4, 8, 16, 24, 32]
HEADROOM_GIB = 1.0     # left free for the OS / display
MIN_CTX = 4096         # below this a model is not worth shipping
BALANCED_CTX = 65536   # what the balanced profile tries to reach first

# Highest fidelity first. f16 is lossless; q4_0 is the cheapest we will ship.
KV_FIDELITY = ["f16", "q8_0", "q5_1", "q4_0"]

PROFILES = {
    "quality":  {
        "kv": ["f16", "q8_0"],
        "blurb": "lossless KV cache, best quantisation, then as much context as fits",
    },
    "balanced": {
        "kv": ["q8_0"],
        "blurb": "q8_0 KV cache, at least 64K context, then the best quantisation",
    },
    "context":  {
        "kv": ["q8_0", "q5_1", "q4_0"],
        "blurb": "most context first, trading KV cache precision down to q4_0 to get it",
    },
}

HEADER = """version = 1

; llama.cpp router preset - {tier} GB VRAM
;
; GENERATED by src/build.py - do not edit.
; Edit configs/<provider>/<model>.ini and re-run: python3 src/build.py
;
;   llama-server --models-dir /path/to/models \\
;                --models-preset dist/vram-{tier:02d}gb.ini \\
;                --host 127.0.0.1 --port 8080
;
; Every section name encodes the whole choice:
;
;   <model>-<quant>-<context>-<kv cache type>
;
; A section applies to the subdirectory of --models-dir whose name is exactly
; that. So pick a line from the table, download that quant into a directory
; named after it, and the context and KV cache settings come with it. No paths
; appear in this file. See README.md.
;
; Each model is listed once per distinct setup that fits in {tier} GB. The
; profile column says what a setup is best at:
;
;   quality   lossless KV cache, best quantisation, then as much context as fits
;   balanced  q8_0 KV cache, at least 64K context, then the best quantisation
;   context   most context first, trading KV cache precision down to q4_0
;
; Profiles that chose the same setup share one line. Figures are gguf-parser
; estimates with flash-attn on and full GPU offload, reserving {headroom:.0f} GiB for
; the OS/display.
;
; Only sections matching a directory you actually have will work. Requesting
; any other one stalls the client until it gives up, so delete the rest.
;
{table};

[*]
stop-timeout = 30
cache-prompt = true
jinja = true
flash-attn = auto
reasoning-format = auto
"""


def load_model_configs():
    """One dict per config, sorted by path."""
    out = []
    for path in sorted(CONFIGS.rglob("*.ini")):
        text = path.read_text()
        m = re.search(r"^\[([^\]]+)\]", text, re.M)
        if not m:
            sys.exit(f"{path}: no [section] found")
        head = text[: m.start()]
        doc = [l for l in head.splitlines() if l.strip().startswith(";")]

        def field(name):
            hit = re.search(rf"^;\s*{name}:\s*(.+)$", head, re.M)
            return hit.group(1).strip() if hit else ""

        cap, body = None, []
        for line in text[m.start():].rstrip().splitlines():
            key = line.split("=", 1)[0].strip() if "=" in line else ""
            if key == "ctx-size":
                cap = int(line.split("=", 1)[1].strip())   # a cap, never exceeded
                continue
            body.append(line)

        title = doc[0].lstrip("; ").strip() if doc else m.group(1)
        out.append({
            "provider": path.parent.name,
            "id": m.group(1).strip(),
            "title": title,
            "params": field("params"),
            "tags": [t.strip() for t in field("tags").split(",") if t.strip()],
            "doc": doc,
            "body": body,
            "cap": cap,
        })
    return out


def vram(data, quant, ctx, kv):
    """VRAM of a (quant, context, KV type) triple.

    KV cost per token does not depend on the weight quant, so every quant's
    curve is the matching reference curve shifted by a constant.
    """
    offset = data["quants"][quant] - data["quants"][data["ref_quant"]]
    return data["ref_curves"][kv][str(ctx)] + offset


def candidates(data, budget, cap, kv_allowed):
    """[(kv, quant, ctx, gib)] that fit the budget."""
    out = []
    for kv in kv_allowed:
        curve = data["ref_curves"].get(kv)
        if not curve:
            continue
        ladder = sorted(int(c) for c in curve)
        if cap:
            ladder = [c for c in ladder if c <= cap]
        for quant in data["quants"]:
            for ctx in ladder:
                if ctx < MIN_CTX and ctx != ladder[-1]:
                    continue
                gib = vram(data, quant, ctx, kv)
                if gib <= budget:
                    out.append((kv, quant, ctx, gib))
    return out


def pick(data, budget, profile, cap):
    """Choose (kv, quant, ctx, gib) for a profile, or None if nothing fits."""
    spec = PROFILES[profile]
    opts = candidates(data, budget, cap, spec["kv"])
    if not opts:
        return None

    qrank = {q: i for i, q in enumerate(sorted(data["quants"], key=lambda q: data["quants"][q]))}
    # higher is better fidelity
    krank = {kv: len(KV_FIDELITY) - KV_FIDELITY.index(kv) for kv in KV_FIDELITY}

    if profile == "quality":
        return max(opts, key=lambda o: (krank[o[0]], qrank[o[1]], o[2]))
    if profile == "context":
        return max(opts, key=lambda o: (o[2], qrank[o[1]], krank[o[0]]))

    # balanced: reach the target context first, then buy quality with the rest
    target = min(BALANCED_CTX, max(o[2] for o in opts))
    good = [o for o in opts if o[2] >= target] or opts
    best_q = max(qrank[o[1]] for o in good)
    return max((o for o in good if qrank[o[1]] == best_q), key=lambda o: o[2])


def ctx_slug(n):
    """Short label for a context length, exact and lossless.

    Models are advertised in either decimal or binary thousands - Gemma's
    128000 and Qwen's 131072 are both called "128K" in the wild - so try
    decimal first and fall back to binary. by_tier() checks the result is
    still unique per model, since a clash would make llama.cpp refuse to
    start with "model 'x' appears multiple times".
    """
    for div, suffix in ((1_000_000, "m"), (1_000, "k")):
        if n % div == 0:
            return f"{n // div}{suffix}"
    if n % 1024 == 0:
        k = n // 1024
        return f"{k // 1024}m" if k % 1024 == 0 else f"{k}k"
    return str(n)


def fmt_ctx(n):
    return ctx_slug(n).upper()


def section_name(model_id, quant, ctx, kv):
    """The section name, which is also the directory name the user must use."""
    return f"{model_id}-{quant.lower()}-{ctx_slug(ctx)}-{kv}"


def plan(est, models):
    """{(tier, profile): [ {**config, kv, quant, ctx, gib} ]}"""
    out = {}
    for tier in TIERS:
        budget = tier - HEADROOM_GIB
        for profile in PROFILES:
            chosen = []
            for cfg in models:
                got = pick(est["models"][cfg["id"]], budget, profile, cfg["cap"])
                if got:
                    kv, quant, ctx, gib = got
                    chosen.append({**cfg, "kv": kv, "quant": quant, "ctx": ctx, "gib": gib})
            if chosen:
                out[(tier, profile)] = chosen
    return out


def by_tier(built):
    """{tier: [entry]}, one entry per distinct setup, profiles merged.

    A model often lands on the same (quant, context, KV) triple under more than
    one profile - always so once it already reaches its maximum context. Those
    become one section listing every profile that chose it, which is the whole
    reason a tier fits in a single file.
    """
    order = list(PROFILES)
    out = {}
    for tier in TIERS:
        merged = {}
        for profile in order:
            for c in built.get((tier, profile), []):
                key = (c["id"], c["quant"], c["ctx"], c["kv"])
                if key in merged:
                    merged[key]["profiles"].append(profile)
                else:
                    merged[key] = {**c, "profiles": [profile], "name": section_name(*key)}
        if not merged:
            continue
        entries = sorted(merged.values(), key=lambda e: (e["id"], order.index(e["profiles"][0])))

        names = [e["name"] for e in entries]
        clashes = sorted({n for n in names if names.count(n) > 1})
        if clashes:
            sys.exit(f"tier {tier}: two different setups share a section name: "
                     + ", ".join(clashes) + "\nfix ctx_slug() in src/build.py")
        out[tier] = entries
    return out


def write_dist(tiers):
    DIST.mkdir(exist_ok=True)
    written = []
    for tier, entries in tiers.items():
        w = max(len(e["name"]) for e in entries)
        table = "".join(
            f";   {e['name']:<{w}}  {'+'.join(e['profiles']):<24}  {e['gib']:5.1f} GiB\n"
            for e in entries
        )
        parts = [HEADER.format(tier=tier, headroom=HEADROOM_GIB, table=table)]
        described = None
        for e in entries:
            parts.append("")
            if e["id"] != described:            # entries are grouped by model
                parts.extend(e["doc"])
                described = e["id"]
            parts.append(f"; {' + '.join(e['profiles'])}: {e['quant']}, {e['ctx']} context, "
                         f"{e['kv']} KV cache (~{e['gib']:.1f} GiB)")
            parts.append(f"[{e['name']}]")
            parts.append(f"ctx-size = {e['ctx']}")
            parts.append(f"cache-type-k = {e['kv']}")
            parts.append(f"cache-type-v = {e['kv']}")
            parts.extend(e["body"][1:])         # body[0] is the config's own [section] line
        path = DIST / f"vram-{tier:02d}gb.ini"
        path.write_text("\n".join(parts) + "\n")
        written.append((path, len(entries), len({e["id"] for e in entries})))
    return written


def render_notes(tiers, est):
    meta = est["_meta"]
    lines = [
        "Ready-to-use llama.cpp router presets, one file per VRAM budget.",
        "",
        "Download the one matching your GPU, then start the server:",
        "",
        "```sh",
        "llama-server --models-dir /path/to/models \\",
        "             --models-preset vram-16gb.ini \\",
        "             --host 127.0.0.1 --port 8080",
        "```",
        "",
        "Weight quantisation, context length and KV cache precision all compete for the same",
        "VRAM. Each file offers three ways to spend it, side by side:",
        "",
        "| Profile | Strategy |",
        "| --- | --- |",
    ]
    for name, spec in PROFILES.items():
        lines.append(f"| `{name}` | {spec['blurb']} |")
    lines += [
        "",
        "Sections are named `<model>-<quant>-<context>-<kv>`, and a section applies to the",
        "`--models-dir` subdirectory with exactly that name. Pick a line, download that quant",
        "into a directory named after it, and the rest of the settings come with it. See the",
        "README for the required layout.",
        "",
        "## Contents",
        "",
        "| File | Models | Setups |",
        "| --- | --- | --- |",
    ]
    for tier, entries in tiers.items():
        lines.append(f"| `vram-{tier:02d}gb.ini` | {len({e['id'] for e in entries})} "
                     f"| {len(entries)} |")

    lines += ["", "## What each file contains", ""]
    for tier, entries in tiers.items():
        lines += [
            f"<details><summary><code>vram-{tier:02d}gb.ini</code> &mdash; "
            f"{len({e['id'] for e in entries})} models, {len(entries)} setups</summary>", "",
            "| Section / directory name | Profiles | Quant | Context | KV cache | Est. VRAM |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for e in entries:
            lines.append(f"| `{e['name']}` | {', '.join(e['profiles'])} | `{e['quant']}` "
                         f"| {fmt_ctx(e['ctx'])} | `{e['kv']}` | {e['gib']:.1f} GiB |")
        lines += ["", "</details>", ""]

    lines += [
        "---", "",
        f"VRAM measured with {meta['tool']}, flash-attention on, full GPU offload. "
        f"Every setup reserves {HEADROOM_GIB:.0f} GiB for the OS/display.",
    ]
    return "\n".join(lines)


def render_models_md(tiers, models):
    """Browsable catalogue: what exists, and what each card gets."""
    where = {}   # model_id -> {tier: [entry]}
    for tier, entries in tiers.items():
        for e in entries:
            where.setdefault(e["id"], {}).setdefault(tier, []).append(e)

    lines = [
        "# Model catalogue",
        "",
        "GENERATED by `src/build.py` - do not edit.",
        "",
        f"{len(models)} models. Use this to find a model, check it fits your card, and see",
        "which quantisation and context you get. See the [README](README.md) to get started.",
        "",
        "## All models",
        "",
        "`Smallest card` is the least VRAM that runs the model at all. `Best context` is the",
        "most context any setup reaches on a 32 GB card.",
        "",
        "| Model | Params | Good at | Smallest card | Best context |",
        "| --- | --- | --- | --- | --- |",
    ]
    for cfg in sorted(models, key=lambda c: c["id"]):
        found = where.get(cfg["id"], {})
        if not found:
            continue
        best = max(e["ctx"] for e in found[max(found)])
        tags = ", ".join(cfg["tags"]) or "text"
        lines.append(f"| [`{cfg['id']}`](#{cfg['id'].replace('.', '')}) | {cfg['params']} "
                     f"| {tags} | {min(found)} GB | {fmt_ctx(best)} |")

    lines += [
        "",
        "## What each card gets",
        "",
        "`Directory name` is what the model's folder under `--models-dir` must be called, and",
        "it is the section name in the preset. Download the quant in the `Quant` column into a",
        "directory with that name.",
        "",
    ]
    for cfg in sorted(models, key=lambda c: c["id"]):
        found = where.get(cfg["id"], {})
        if not found:
            continue

        lines += [
            f"### {cfg['id']}",
            "",
            cfg["title"],
            "",
            "| Card | Profiles | Quant | Directory name | VRAM |",
            "| --- | --- | --- | --- | --- |",
        ]
        for tier in sorted(found):
            for e in found[tier]:
                lines.append(f"| {tier} GB | {', '.join(e['profiles'])} | `{e['quant']}` "
                             f"| `{e['name']}` | {e['gib']:.1f} GiB |")
        lines.append("")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--notes", action="store_true",
                    help="print release notes to stdout instead of writing dist/")
    args = ap.parse_args()

    est = json.loads((CONFIGS / "vram-estimates.json").read_text())
    models = load_model_configs()

    needed = {kv for spec in PROFILES.values() for kv in spec["kv"]}
    incomplete = []
    for cfg in models:
        data = est["models"].get(cfg["id"], {})
        if not data.get("quants") or not needed <= set(data.get("ref_curves", {})):
            incomplete.append(cfg["id"])
    if incomplete:
        sys.exit("missing measurements for: " + ", ".join(incomplete)
                 + "\nrun: python3 src/measure.py --missing")

    tiers = by_tier(plan(est, models))

    if args.notes:
        print(render_notes(tiers, est))
        return

    for path, setups, n in write_dist(tiers):
        print(f"wrote {path.relative_to(ROOT)}  ({n} models, {setups} setups)")

    # Committed, unlike dist/, so it can be browsed on GitHub. CI checks it is fresh.
    catalogue = ROOT / "MODELS.md"
    catalogue.write_text(render_models_md(tiers, models))
    print(f"wrote {catalogue.relative_to(ROOT)}  ({len(models)} models)")


if __name__ == "__main__":
    main()
